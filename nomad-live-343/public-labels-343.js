(()=>{
'use strict';
/* Ball46 public-label alias layer. Presentation only: no API, odds, engine, signal or statistics logic. */
const SKIP=new Set(['SCRIPT','STYLE','TEMPLATE','NOSCRIPT']);
function pageLabel(){
  const p=location.pathname.toLowerCase();
  const body=document.body;
  if(body?.dataset?.page==='live'||/\/(?:index\.html)?$/.test(p))return'BALL46 · LIVE MATCH CENTER';
  if(body?.classList?.contains('ball46-product-signals')||p.endsWith('/signal.html'))return'BALL46 · LIVE SIGNAL CENTER';
  if(body?.classList?.contains('ball46-product-statistics')||p.endsWith('/statistics.html'))return'BALL46 · PERFORMANCE CENTER';
  if(p.endsWith('/signal-next.html')||p.endsWith('/statistics-next.html')||p.endsWith('/dashboard-v2.html'))return'BALL46 · PREVIEW';
  return'BALL46';
}
function aliasText(input){
  let s=String(input??'');
  if(!s)return s;
  s=s.replace(/NOMAD LIVE 3\.43 · DASHBOARD V2 PREVIEW/g,'BALL46 · LIVE DASHBOARD PREVIEW');
  s=s.replace(/NOMAD LIVE 3\.43 · BULK DASHBOARD/g,'BALL46 · LIVE MATCH CENTER');
  s=s.replace(/NOMAD LIVE 3\.43 · PREVIEW/g,'BALL46 · PREVIEW');
  s=s.replace(/NOMAD LIVE 3\.43/g,pageLabel());
  s=s.replace(/NOMAD 3\.43 · 5USD API Monitor/g,'BALL46 · 5USD API Monitor');
  s=s.replace(/NOMAD 3\.43 · Owner monitor/g,'BALL46 · Owner monitor');
  s=s.replace(/3\.43 · OWNER · 5USD API CONTROL CENTER/g,'OWNER · 5USD API CONTROL CENTER');
  s=s.replace(/3\.43 · ALL MARKET ENGINE/g,'ALL MARKET ENGINE');
  s=s.replace(/ตั้งค่า Engine 3\.43 ·/g,'ตั้งค่า Engine ·');
  s=s.replace(/nomadtips3 · Owner Settings 3\.43/gi,'Ball46 · Owner Settings');
  s=s.replace(/CEO AUTO · ADD K/g,'ANALYSIS ENGINE 01 · ANALYSIS ENGINE 02');
  s=s.replace(/CEO · ADD K PERFORMANCE/g,'ANALYSIS ENGINE PERFORMANCE');
  s=s.replace(/CEO · ADD K/g,'ENGINE 01 · ENGINE 02');
  s=s.replace(/OWNER \+ CEO/g,'DUAL ANALYSIS');
  s=s.replace(/CEO SCORE/g,'ANALYSIS SCORE');
  s=s.replace(/CEO Decision · Add K/gi,'Analysis Decision');
  s=s.replace(/CEO Auto Gate Passed/g,'Analysis Gate Passed');
  s=s.replace(/Strategy CEO v/g,'Analysis Engine 01 · v');
  s=s.replace(/OWNER CONDITIONS · SAME MATCH/g,'SECONDARY ANALYSIS · SAME MATCH');
  s=s.replace(/Settled results generated by the CEO strategy only\./g,'Settled results generated by the analysis engine.');
  s=s.replace(/Waiting for settled CEO results…/g,'Waiting for settled analysis results…');
  s=s.replace(/CEO results will appear here after settlement\./g,'Analysis-engine results will appear here after settlement.');
  s=s.replace(/\b(\d+) CEO\b/g,'$1 ENGINE 01');
  return s;
}
function paintTextNode(node){
  const p=node.parentElement;
  if(!p||SKIP.has(p.tagName))return;
  const next=aliasText(node.nodeValue);
  if(next!==node.nodeValue)node.nodeValue=next;
}
function paint(root=document){
  if(document.title){const t=aliasText(document.title);if(t!==document.title)document.title=t}
  const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
  let node;while((node=walker.nextNode()))paintTextNode(node);
}
let queued=false;
function queue(){if(queued)return;queued=true;queueMicrotask(()=>{queued=false;paint(document)})}
function start(){paint(document);new MutationObserver(queue).observe(document.documentElement,{childList:true,subtree:true,characterData:true})}
if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',start,{once:true});else start();
window.BALL46_PUBLIC_LABELS={mode:'PRESENTATION_ONLY',aliasText,refresh:()=>paint(document)};
})();
